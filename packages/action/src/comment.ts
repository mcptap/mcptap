// Renders a Markdown PR comment for an mcptap run, optionally augmented with
// a tool-description score report. Includes a hidden marker so subsequent runs
// can find + edit instead of post anew.

import type { RunOutput, ScoreReport, TestResult, ToolScore } from 'mcptap';

export const COMMENT_MARKER = '<!-- mcptap:run -->';

export function renderPrComment(run: RunOutput, score?: ScoreReport): string {
  const { totals, status, slug, duration_ms } = run;
  const heading =
    status === 'pass'
      ? `### mcptap · ${slug} · all green (${totals.total} test${totals.total === 1 ? '' : 's'})`
      : `### mcptap · ${slug} · ${totals.failed} failed`;

  const meta: string[] = [];
  if (run.meta.commit_sha) {
    meta.push(`commit \`${run.meta.commit_sha.slice(0, 7)}\``);
  }
  if (run.meta.branch) {
    meta.push(`branch \`${run.meta.branch}\``);
  }
  meta.push(formatDuration(duration_ms));

  const lines: string[] = [];
  lines.push(COMMENT_MARKER);
  lines.push('');
  lines.push(heading);
  lines.push('');
  lines.push(meta.map((m) => `_${m}_`).join(' · '));
  lines.push('');

  // Results table
  lines.push('| | Test | Duration | Notes |');
  lines.push('| - | - | - | - |');
  for (const r of run.results) {
    lines.push(
      `| ${glyph(r)} | ${escapeMd(r.name)} | ${formatDuration(r.duration_ms)} | ${notes(r)} |`,
    );
  }
  lines.push('');

  // Snapshot warnings
  const drift = run.results.filter((r) => r.snapshot?.status === 'mismatch');
  if (drift.length > 0) {
    lines.push('#### Snapshot drift');
    lines.push('');
    for (const r of drift) {
      lines.push(`<details><summary><b>${escapeMd(r.name)}</b></summary>`);
      lines.push('');
      lines.push('```diff');
      lines.push(r.snapshot?.diff ?? '');
      lines.push('```');
      lines.push('</details>');
      lines.push('');
    }
  }

  // Errors (non-snapshot)
  const errors = run.results.filter(
    (r) => r.status === 'fail' && r.snapshot?.status !== 'mismatch' && r.error,
  );
  if (errors.length > 0) {
    lines.push('#### Failures');
    lines.push('');
    for (const r of errors) {
      lines.push(`<details><summary><b>${escapeMd(r.name)}</b></summary>`);
      lines.push('');
      lines.push('```');
      lines.push(r.error?.message ?? '');
      lines.push('```');
      lines.push('</details>');
      lines.push('');
    }
  }

  // Tool-description quality scores
  if (score) {
    lines.push(...renderScoreSection(score));
  }

  lines.push('---');
  lines.push(
    `Generated by [mcptap](https://github.com/mcptap/mcptap) · schema_version ${run.schema_version}`,
  );

  return lines.join('\n');
}

function renderScoreSection(score: ScoreReport): string[] {
  const lines: string[] = [];
  const { summary, tools } = score;

  const grade =
    summary.average >= 85 ? '🟢' : summary.average >= 65 ? '🟡' : '🔴';

  lines.push(
    `#### ${grade} Tool-description quality · average ${summary.average}/100 · ${summary.total_tokens.toLocaleString('en-US')} tokens`,
  );
  lines.push('');

  // Sort: lowest scores first (most actionable)
  const sorted = [...tools].sort((a: ToolScore, b: ToolScore) => a.score - b.score);
  const flagged = sorted.filter((t) => t.score < 100);

  if (flagged.length === 0) {
    lines.push(`_All ${tools.length} tool${tools.length === 1 ? '' : 's'} scored 100/100._`);
    lines.push('');
    return lines;
  }

  lines.push('| Tool | Score | Tokens | Top issue |');
  lines.push('| - | - | - | - |');
  for (const tool of flagged) {
    const top = tool.issues
      .slice()
      .sort((a, b) => b.penalty - a.penalty)[0];
    const issueText = top ? `${top.message}` : '';
    lines.push(
      `| \`${tool.name}\` | ${scoreCell(tool)} | ${tool.tokens} | ${escapeMd(issueText)} |`,
    );
  }
  lines.push('');

  if (sorted.length > flagged.length) {
    const passing = sorted.length - flagged.length;
    lines.push(`_${passing} other tool${passing === 1 ? '' : 's'} scored 100/100._`);
    lines.push('');
  }

  return lines;
}

function scoreCell(tool: ToolScore): string {
  if (tool.score >= 85) return `🟢 ${tool.score}`;
  if (tool.score >= 65) return `🟡 ${tool.score}`;
  return `🔴 ${tool.score}`;
}

function glyph(r: TestResult): string {
  if (r.status === 'pass') {
    if (r.snapshot?.status === 'created') return '🆕';
    if (r.snapshot?.status === 'updated') return '🔄';
    return '✅';
  }
  if (r.status === 'fail') return '❌';
  return '⏭️';
}

function notes(r: TestResult): string {
  if (r.snapshot) {
    switch (r.snapshot.status) {
      case 'created':
        return 'snapshot created';
      case 'updated':
        return 'snapshot updated';
      case 'matched':
        return 'snapshot matched';
      case 'mismatch':
        return '**snapshot drift**';
    }
  }
  if (r.status === 'fail' && r.error) {
    const first = r.error.message.split('\n')[0]?.slice(0, 80) ?? '';
    return escapeMd(first);
  }
  return '';
}

function formatDuration(ms: number): string {
  if (ms < 1) return '<1ms';
  if (ms < 1000) return `${Math.round(ms)}ms`;
  return `${(ms / 1000).toFixed(2)}s`;
}

function escapeMd(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}
